import pandas as pd
import matplotlib.pyplot as plt
import numpy as np

def plot_results(csv_file, run_id='', skiprows=[]):
    """
    Plot results from the csv file generated by  benchmark_prefect.py 
    """
    # Load results from CSV
    if skiprows:
        exclude_headerrow = ''
        if 0 in skiprows:
            skiprows = skiprows.remove(0)
            exclude_headerrow = ' row 0 (header) is excluded.'
        print(f'Skipping rows: {skiprows} {exclude_headerrow}')
    df_all = pd.read_csv(csv_file, skiprows = skiprows)
    if run_id=='':
        df = df_all
    else:
        df = df_all[df_all["run_id"]==run_id]
    print(f'{len(df)} rows selected from {csv_file}')
    # Plot results
    fig, ax = plt.subplots(figsize=(10, 5))
    #plt.figure(figsize=(10, 5))
    for runner in np.unique(df["runner"]):
        df_subset = df[df["runner"] == runner]
        for n_processes in np.unique(df_subset["n_processes"]):
            #runner_name = runner.split('.')[-1].replace("'>",'')
            df_subsubset = df_subset[df_subset["n_processes"] == n_processes ]
            for t_min_sleep in np.unique(df_subsubset["t_min_sleep"]):
                df_result = df_subsubset[df_subsubset["t_min_sleep"] == t_min_sleep]
                t_max_sleep = df_result["t_max_sleep"].iloc[0]
                workflow_type = df_result["workflow_type"].iloc[0]
                nthreads = df_result["n_threads_per_process"].iloc[0]
                n_parallelism = df_result["n_parallelism"].iloc[0]
                if "n_subflows" in df_result.columns:
                    ntasks = df_result["n_subflows"]
                else:
                    ntasks = df_result["n_tasks"]
                ax.plot(
                    ntasks, # number of tasks or subflows
                    df_result["t_workflow"],
                    #label=f"{workflow_type}-{runner}: T_workflow (nthreads={nthreads}, n_processes={n_processes}, n_parallelism={n_parallelism}, "
                    label=f"{runner}: T_workflow (n_thr_per_proc={nthreads}, n_proc={n_processes}, n_para={n_parallelism}, "
                    f"t_min_sleep={t_min_sleep}, t_max_sleep={t_max_sleep})",
                    marker="o",
                )
                ax.plot(
                    ntasks,
                    df_result["t_sum_task_times_per_unit_of_parallelism"],
                    #label=f"{workflow_type}-{runner}: T_sum_task_times_per_unit_of_parallelism (nthreads={nthreads}, n_processes={n_processes}, "
                    label=f"{runner}: T_sum_task_times_per_unit_of_parallelism (n_thr_per_proc={nthreads}, n_proc={n_processes}, "
                    f"n_para={n_parallelism}, t_min_sleep={t_min_sleep}, t_max_sleep={t_max_sleep})",
                    marker="s",
                )

    ax.set_xlabel("Number of Tasks/Subflows")
    ax.set_ylabel("Time (s)")
    # plt.xscale("log")
    # plt.yscale("log")
    ax.legend(bbox_to_anchor=(1.04, 1))
    # plt.title("Dask Scheduler Overhead Analysis")
    first_row_data = df.iloc[0]
    title = (f"system: {first_row_data['system_name']}, "
    f"mem:{first_row_data['total_memory']}GB, "
    #f"min_sleep:{first_row_data['t_min_sleep']}, "
    #f"max_sleep:{first_row_data['t_max_sleep']}, "
    f"start time:{first_row_data['date_and_time']} "
    f"({first_row_data['developer']})")
    workflow_framework = first_row_data['workflow_orchestration_framework']
    plt.title(title)
    fig.suptitle(f"{workflow_framework.capitalize()} Scheduler Benchmark Timging Analysis")
    plt.grid()
    plt.savefig(f"{workflow_framework}_benchmark_timing.png", bbox_inches="tight")

    fig, ax = plt.subplots(figsize=(10, 5))
    #plt.figure(figsize=(10, 5))
    for runner in np.unique(df["runner"]):
        df_subset = df[df["runner"] == runner]
        for n_processes in np.unique(df_subset["n_processes"]):
            df_subsubset = df_subset[df_subset["n_processes"] == n_processes ]    
            for t_min_sleep in np.unique(df_subsubset["t_min_sleep"]):
                df_result = df_subsubset[df_subsubset["t_min_sleep"] == t_min_sleep]
                t_max_sleep = df_result["t_max_sleep"].iloc[0]
                workflow_type = df_result["workflow_type"].iloc[0]
                n_threads = df_result["n_threads_per_process"].iloc[0]
                n_parallelism = df_result["n_parallelism"].iloc[0]
                if "n_subflows" in df_result.columns:
                    ntasks = df_result["n_subflows"]
                else:
                    ntasks = df_result["n_tasks"]
                ax.plot(
                    ntasks,
                    df_result["overhead_percentage"],
                    #label=f"{workflow_type}-{runner}: n_threads={n_threads}, n_processes={n_processes}, n_parallelism={n_parallelism}, t_min_sleep={t_min_sleep}, t_max_sleep={t_max_sleep}",
                    label=f"{runner}: n_thr_per_proc={n_threads}, n_proc={n_processes}, n_para={n_parallelism}, "
                    f"t_min_sleep={t_min_sleep}, t_max_sleep={t_max_sleep}",
                    marker="s",
                )

    ax.set_xlabel("Number of Tasks/Subflows")
    ax.set_ylabel("Percentage Overhead")
    # plt.xscale("log")
    # plt.yscale("log")
    ax.legend(bbox_to_anchor=(1.04, 1))
    # Put some common info in the title. 
    # Get the info from the first row
    plt.title(title)
    fig.suptitle(f"{workflow_framework.capitalize()} Schedular Benchmark Overhead Analysis")
    # plt.title("Dask Scheduler Overhead Analysis")
    plt.grid()
    plt.savefig(f"{workflow_framework}_benchmark_overhead.png", bbox_inches="tight")

    fig, ax = plt.subplots(figsize=(10, 5))
    #plt.figure(figsize=(10, 5))
    for runner in np.unique(df["runner"]):
        df_subset = df[df["runner"] == runner]
        for n_processes in np.unique(df_subset["n_processes"]):
            df_subsubset = df_subset[df_subset["n_processes"] == n_processes ]    
            for t_min_sleep in np.unique(df_subsubset["t_min_sleep"]):
                df_result = df_subsubset[df_subsubset["t_min_sleep"] == t_min_sleep]
                t_max_sleep = df_result["t_max_sleep"].iloc[0]
                workflow_type = df_result["workflow_type"].iloc[0]
                n_threads = df_result["n_threads_per_process"].iloc[0]
                n_parallelism = df_result["n_parallelism"].iloc[0]
                if "n_subflows" in df_result.columns:
                    ntasks = df_result["n_subflows"]
                else:
                    ntasks = df_result["n_tasks"]
                ax.plot(
                    ntasks,
                    df_result["overhead_per_task_seconds"],
                    #label=f"{workflow_type}-{runner}: n_threads={n_threads}, n_processes={n_processes}, n_parallelism={n_parallelism}, t_min_sleep={t_min_sleep}, t_max_sleep={t_max_sleep}",
                    label=f"{runner}: n_thr_per_proc={n_threads}, n_proc={n_processes}, n_para={n_parallelism}, "
                    f"t_min_sleep={t_min_sleep}, t_max_sleep={t_max_sleep}",
                    marker="s",
                )

    ax.set_xlabel("Number of Tasks/Subflows")
    ax.set_ylabel("Percentage Overhead Per Task Seconds (s)")
    # plt.xscale("log")
    # plt.yscale("log")
    ax.legend(bbox_to_anchor=(1.04, 1))
    # Put some common info in the title. 
    # Get the info from the first row
    plt.title(title)
    fig.suptitle(f"{workflow_framework.capitalize()} Schedular Benchmark Overhead Per Task Second Analysis")
    # plt.title("Dask Scheduler Overhead Analysis")
    plt.grid()
    plt.savefig(f"{workflow_framework}_benchmark_overhead_per_task_seconds.png", bbox_inches="tight")
    plt.show()

